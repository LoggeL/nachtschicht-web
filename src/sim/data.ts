export function computeIntelCompletion(
  target: HeistTarget,
  discoveredNodeIds: string[],
  timedGuardIds: string[]
): number {
  const discoverableNodes = target.nodes.filter(
    (n) => n.kind !== 'getaway_zone' && n.kind !== 'stairs'
  );
  const total = discoverableNodes.length + target.guards.length;
  if (total === 0) return 100;
  const foundNodes = discoverableNodes.filter((n) =>
    discoveredNodeIds.includes(n.id)
  ).length;
  const foundGuards = target.guards.filter((g) =>
    timedGuardIds.includes(g.id)
  ).length;
  return Math.min(100, Math.round(((foundNodes + foundGuards) / total) * 100));
}

export function createInitialIntel(
  target: HeistTarget,
  hasBlueprintUpgrade = false
): IntelState {
  const discoveredNodeIds = target.nodes
    .filter((n) => n.visibleFromStreet)
    .map((n) => n.id);
  const timedGuardIds = target.guards
    .filter((g) => g.visibleFromStreet)
    .map((g) => g.id);
  const scoutedRoomIds = target.rooms
    .filter((r) => r.initiallyScouted)
    .map((r) => r.id);

  if (hasBlueprintUpgrade) {
    // Reveal one extra interior non-hidden node
    const bonusNode = target.nodes.find(
      (n) => !n.visibleFromStreet && !n.isHiddenHazard && !discoveredNodeIds.includes(n.id)
    );
    if (bonusNode) discoveredNodeIds.push(bonusNode.id);
  }

  return {
    targetId: target.id,
    discoveredNodeIds,
    timedGuardIds,
    scoutedRoomIds,
    completionPercent: computeIntelCompletion(
      target,
      discoveredNodeIds,
      timedGuardIds
    ),
    blueprintPurchased: hasBlueprintUpgrade,
  };
}

